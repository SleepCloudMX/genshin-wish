/* 算法 —— 从"算不动"到"能实时算"的几步降维，依据 docs/algorithms.md 与项目优化记录 */
(function (global) {
  'use strict';
  var W = global.Wish = global.Wish || {};
  var M = W.modules = W.modules || {};

  function row(cells) {
    return '<tr>' + cells.map(function (c, i) {
      return i === 0 ? '<th scope="row">' + c + '</th>' : '<td>' + c + '</td>';
    }).join('') + '</tr>';
  }

  /* n = 500 的实测数字直接从实验数据里取，避免正文与图表脱节 */
  function benchLine() {
    var A = global.__WISH_ANALYSIS__;
    var fallback = '实测耗时见 <a href="#/perf">性能与验证</a>。';
    if (!A) return fallback;
    var i = A.task1.n.indexOf(500);
    if (i < 0) return fallback;
    var g = A.task1.series['dp-golds'].time[i];
    var s = A.task1.series['dp-state'].time[i];
    if (g === null || s === null) return fallback;
    return '本机实测：n = 500 时 dp-state 要 ' + s.toFixed(0) + ' ms，dp-golds 只要 ' +
      g.toFixed(0) + ' ms，快约 ' + (s / g).toFixed(0) + ' 倍。';
  }

  var DOC_HEAD = '' +
    '<p>精确算出 n 个 UP 的抽数分布，最直接的写法在 n 稍大时就跑不动了。' +
    '这一页记录这个项目把它一步步压下来的过程：每一步砍掉的是哪个维度、代价转移到了哪里。' +
    '每一步的实测耗时见 <a href="#/perf">性能与验证</a>。</p>' +

    '<h2>要算的是什么</h2>' +
    '<p>同一个模型要回答三个问题：</p>' +
    '<div class="tablewrap"><table class="dtable dtable--plain">' +
    '<thead><tr><th>任务</th><th>输入</th><th>输出</th></tr></thead><tbody>' +
    row(['任务 1', '目标 UP 数 n、初始状态', '抽到 n 个限定所需抽数的分布 P(抽数)']) +
    row(['任务 2', '任务 1 的输入 + 常驻数量', '每个常驻数量下的条件分布 P(抽数 | 常驻数)']) +
    row(['任务 3', '任务 1 的输入', '歪出多少个常驻的分布 P(常驻数)']) +
    '</tbody></table></div>' +
    '<p>三者是一回事：任务 1 = 任务 3 加权任务 2，即 P(抽数) = Σ P(常驻数) · P(抽数 | 常驻数)。' +
    '下面以任务 1 为主线，任务 2、任务 3 只是在状态里多带一个量。</p>' +

    '<h2>起点：逐抽推进</h2>' +
    '<p>最直觉的写法是按抽推进。状态记作（抽数 i, 已获得 UP 数 j, 已连歪次数 s），' +
    '每抽转移到 i+1，出金时再按 p_up[s] 分裂成「中」和「歪」两条支路。</p>' +
    '<p>代价立刻失控。抽数轴本身有 180n 长——每个 UP 最多消耗 2 个金、每金最多 90 抽，' +
    'n = 500 时就是 9 万；状态格数是 4 × n × 180n 的量级；而且每格都要和长度为 91 的金分布' +
    '做一次卷积，量级 O(n²·m²)。实测 n = 7 要 24.8 ms、n = 10 要 56.7 ms，n 再大就完全不可用。' +
    '它还带不动第二个目标：要同时统计歪出了几个常驻，状态里就得再加一维，代价再乘 n。</p>' +
    '<p>问题出在「抽数」这个维度被过早引入了。抽数只有在最后一步才真正需要——' +
    '中途真正要算的是「一共需要几个金」，以及「这么多金要多少抽」。</p>' +

    '<h2>第一步：只枚举中／歪，抽数留到最后（dp-path）</h2>' +
    '<p>n 次 UP 的中／歪组合一共 2ⁿ 条。每条序列只记两个数：消耗的金数（中记 1、歪记 2）' +
    '和歪的次数（就是歪出的常驻数）。把金数相同的序列概率相加，得到「需要 g 个金」的分布，' +
    '再与预先算好的「g 个金要多少抽」加权合成抽数分布。</p>' +
    '<p>这样每一步都是标量运算，n ≤ 10 时只要 0.5 ms，比逐抽推进快两个数量级。' +
    '代价是序列数随 n 指数增长：n = 20 是一百万条（约 0.6 s），n = 30 就是十亿条，到此为止。</p>' +

    '<h2>第二步：不枚举序列，按状态聚合（dp-state）</h2>' +
    '<p>关键在于：状态转移只依赖当前的连歪次数，与怎么走到这里的无关。' +
    '所以到达同一状态的序列可以整体合并——只保留「到达状态 s 的抽数分布」，' +
    '每步对 4 个状态各做一次卷积，把概率质量往前推一层。</p>' +
    '<p>序列维度就此消失，代价是抽数维度又回来了：每一步都要卷积长度为 O(k·m) 的数组，' +
    '复杂度 O(n²·m·log(n·m))。n = 500 从「跑不动」变成「几秒」。</p>' +

    '<h2>第三步：DP 只数金，抽数最后卷一次（dp-golds，当前默认）</h2>' +
    '<p>再往前推一步：既然代价只取决于「一共出了几个金」，那 DP 里根本不必带着抽数。' +
    '状态缩成（连歪次数, 金数）两维，纯整数运算，复杂度 O(n²)——与单个金的抽数上限 m 无关。</p>' +
    '<p>抽数留到最后一次性引入：「需要 g 个金」的概率，与缓存好的「g 个金要多少抽」的分布' +
    '加权相加即可。多金分布只跟池子有关，与垫抽、大保底这些初始状态无关，算一次就能一直用。' +
    '初始状态只在最后那一次卷积里体现：垫了 p 抽，就是把第一个金的分布右移再截断；' +
    '大保底则相当于白送一个金，末尾再卷一次普通出金分布。</p>' +
    '<p>%BENCH%</p>' +
    '<p>顺带把三个任务一并解决：状态里多带一个「歪出的常驻数」，仍然只做整数 DP，' +
    '任务 2、任务 3 不需要另起炉灶。</p>' +

    '<h2>再大就换近似（CLT，n &gt; 500）</h2>' +
    '<p>n 很大时，总抽数近似服从正态分布。这里有个容易忽略的细节：各次 UP 的连歪状态并不固定，' +
    '它会从初始值迁移到稳态分布，所以第一个 UP 用初始状态的精确矩、其余 n−1 个用稳态矩，' +
    '两者相加再取正态，最后用 ±0.5 的连续性修正落到整数抽数上。复杂度 O(1)，' +
    'n = 500 时相对误差已降到 0.001% 量级。近似误差的收敛曲线见 <a href="#/perf">性能与验证</a>。' +
    '（网页界面的目标 UP 数上限目前是 30，都走精确解。）</p>' +

    '<h2>各方案对照</h2>' +
    '<div class="tablewrap"><table class="dtable dtable--plain">' +
    '<thead><tr><th>方案</th><th>复杂度</th><th>现在的位置</th></tr></thead><tbody>' +
    row(['dp-pulls', 'O(n²·m²)', '直觉起点，只作基准线，已不用']) +
    row(['dp-path', 'O(2ⁿ)', '小 n 最快；n ≤ 20 可用于交叉校验']) +
    row(['dp-state', 'O(n²·m·log(n·m))', '可显式调用；曾是首选，现被 dp-golds 取代']) +
    row(['dp-golds', 'O(n²) + 一次性加权卷积', '当前默认，三个任务通吃']) +
    row(['dp-state-golds', 'O(n³·m·log(n·m))', '理论可行，常数远大于 dp-golds，未实现']) +
    row(['CLT', 'O(1)', 'n &gt; 500 的近似通道']) +
    '</tbody></table></div>' +

    '<h2>为什么没走 FFT 这条路</h2>' +
    '<p>卷积看着像瓶颈，实测却不是：numpy 的卷积在 100–90000 的长度上已经比 FFT 实现更快，' +
    '而 FFT 的幂次法（对分布做 k 次自卷积）在 k = 101 时误差已经到 2.0，数值上不可用。' +
    '真正省时间的做法是绕开卷积本身——也就是 dp-golds：先用整数 DP 把序列维度消掉，' +
    '最后只卷一次。</p>' +

    '<h2>数值精度</h2>' +
    '<p>全部计算用双精度浮点，没有截断、没有近似（CLT 分支除外）。舍入误差的量级：</p>' +
    '<div class="tablewrap"><table class="dtable dtable--plain">' +
    '<thead><tr><th>环节</th><th>相对误差量级</th></tr></thead><tbody>' +
    row(['单金分布构造', '~4×10⁻¹⁴']) +
    row(['多金分布卷积（k 次）', '~k × 2×10⁻¹⁴']) +
    row(['dp-golds（n = 500，约 1000 次卷积）', '~2×10⁻¹¹']) +
    row(['稳态权重的归一化偏差', '~4×10⁻⁷（系统性，已计入模型）']) +
    '</tbody></table></div>' +
    '<p>卷积的相对误差与数值大小成正比，小到 10⁻⁵⁰ 的尾部概率和大到 0.1 的主体概率' +
    '相对精度相同，不会因为极端幸运的尾部而失真。这些量级都远小于模型本身的偏差，' +
    '见 <a href="#/about">模型与误差</a>。</p>';

  M.algo = {
    id: 'algo',
    title: '算法',
    group: '关于',
    layout: 'doc',
    intro: '直接算在 n 稍大时就跑不动。这里记录每一步优化砍掉了哪个维度、代价转移到了哪里。',
    defaultView: 'doc',
    defaults: {},
    controls: function () { return []; },
    views: {
      doc: {
        label: '说明',
        render: function (host) {
          var box = global.document.createElement('div');
          box.className = 'prose';
          box.innerHTML = DOC_HEAD.replace('%BENCH%', benchLine());
          host.appendChild(box);
        }
      }
    }
  };
})(typeof globalThis !== 'undefined' ? globalThis : this);
